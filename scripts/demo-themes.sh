#!/usr/bin/env bash
# Runs every theme of examples/themes one after another, so they can all be
# watched (and checked) hands-off. Each theme blanks the screen after IDLE
# seconds of inactivity, stays on screen for SHOW seconds and is then stopped.
# Themes whose programs are not installed are skipped. At the end, a summary
# flags any theme that failed to start or woke the screen by itself.
#
# This runs on your REAL screen. Don't touch the mouse or keyboard while it
# runs: any input wakes the screen and spoils that theme's result. Ctrl+C
# stops it at any time. To watch it in a window instead, run it inside a
# nested compositor:
#
#   dbus-run-session -- labwc -C scripts/nested-labwc -s scripts/demo-themes.sh
#
# Usage:
#   scripts/demo-themes.sh              # every theme
#   ONLY=maze scripts/demo-themes.sh    # only themes whose name contains "maze"
#   SHOW=30 scripts/demo-themes.sh      # keep each theme on screen longer
#
# Settings (environment variables):
#   IDLE  seconds of inactivity before each theme starts (default 1)
#   SHOW  seconds each theme stays on screen (default 5)
#   ONLY  run only the themes whose name contains this text
#   DIR   working directory for sample files and logs (default
#         ~/wayvoid-test; delete it when done)
#
# Requires ffmpeg (to generate the sample files; nothing is downloaded). Each
# theme lists what it needs in its THEME_REQUIRES line.
set -u
cd "$(dirname "$0")/.."

IDLE=${IDLE:-1}
SHOW=${SHOW:-5}
ONLY=${ONLY:-}
DIR=${DIR:-$HOME/wayvoid-test}
LOGS=$DIR/logs
THEMES=$PWD/examples/themes

command -v ffmpeg >/dev/null || { echo "ffmpeg is required to generate the sample files" >&2; exit 1; }
cargo build --release --quiet --features theme || exit 1
W=$PWD/target/release/wayvoid

# --- Sample files for the video theme, generated once -----------------------
mkdir -p "$DIR/slides" "$LOGS"
lavfi() { ffmpeg -loglevel error -f lavfi "$@"; }
[ -e "$DIR/video.mp4" ] || lavfi -i testsrc2=s=1280x720:r=30 -t 10 "$DIR/video.mp4"
[ -e "$DIR/anim.gif" ] || lavfi -i mandelbrot=s=480x270 -t 4 "$DIR/anim.gif"
[ -e "$DIR/slides/1.png" ] || lavfi -i cellauto=s=1280x720:rule=110 -frames:v 5 -start_number 1 "$DIR/slides/%d.png"

# --- Helpers ------------------------------------------------------------------
# What some themes need, as a program `run` can look for.
BROWSER=$(command -v google-chrome-stable || command -v chromium || command -v firefox || echo chromium)
PYGAME=$(python3 -c 'import pygame' >/dev/null 2>&1 && echo python3 || echo pygame)

pid=
trap '[ -n "$pid" ] && kill "$pid" 2>/dev/null; echo; echo "Interrupted."; exit 130' INT TERM

results=()

# How a theme went, according to wayvoid's log.
verdict() {
    if ! grep -q "screen blanked" "$1"; then echo "NEVER BLANKED (input or inhibitor)"
    elif grep -q 'theme ".*": ' "$1"; then echo "FAIL: could not start"
    elif grep -q "too soon" "$1"; then echo "FAIL: theme exited right away"
    elif grep -q "screen restored" "$1"; then echo "WOKE UP before the end (input or inhibitor)"
    elif grep -q "restarting" "$1"; then echo "ok (theme exited and was restarted)"
    else echo ok
    fi
}

# run NAME REQUIRED-PROGRAM THEME [ARGS...]
# Runs wayvoid with THEME (blank, or a file of examples/themes) and ARGS,
# unless REQUIRED-PROGRAM is missing.
run() {
    local name=$1 need=$2 theme=$3
    shift 3
    [[ -n $ONLY && $name != *"$ONLY"* ]] && return
    if ! command -v "$need" >/dev/null; then
        printf '  %-18s skipped (%s not installed)\n' "$name" "$need"
        results+=("$name|skipped: $need not installed")
        return
    fi
    [[ $theme != blank ]] && theme=$THEMES/$theme
    printf '▶ %-18s starts in %ss, shown for %ss. Hands off...\n' "$name" "$IDLE" "$SHOW"
    "$W" "$IDLE" "$theme" "$@" > "$LOGS/$name.out" 2> "$LOGS/$name.log" &
    pid=$!
    sleep $((IDLE + SHOW))
    kill "$pid" 2>/dev/null
    wait "$pid" 2>/dev/null
    pid=
    results+=("$name|$(verdict "$LOGS/$name.log")")
    sleep 2
}

# --- Themes -------------------------------------------------------------------
#   NAME              NEEDS         THEME        ARGUMENTS
run blank             "$W"          blank

# Terminal
run matrix            cmatrix       matrix       --color cyan --background 001018
run matrix-live       cmatrix       matrix-live  --color red
run marquee           figlet        marquee      --font slant --background 101828 "wayvoid"
run marquee-live      figlet        marquee      --transparent --color cyan "wayvoid"
run clock             tty-clock     clock        --color yellow --background 1a1a2e
run clock-still       tty-clock     clock        --still --color red
run jumpclock         figlet        jumpclock    --font slant --color cyan 2
run aquarium          asciiquarium  aquarium     --background 001a33
run pipes             pipes.sh      pipes        --count 5 --background 202020
run bonsai            cbonsai       bonsai       --message "wayvoid" --background 0d1a0d

# Generated by FFmpeg
run mandelbrot        ffplay        mandelbrot
run life              ffplay        life         --color ff8800 --background 100800

# Videos, GIFs and images
run video             mpv           video        "$DIR/video.mp4" "$DIR/anim.gif"
run video-slides      mpv           video        --image-time 2 "$DIR/slides/"

# 3D and shaders
run text3d            "$BROWSER"    text3d       --color gold --background "#102030" "wayvoid"
run maze3d            "$BROWSER"    maze3d       --size 6 --speed 1.5 --color 30
run pipes3d           "$PYGAME"     pipes3d      --speed 30 --background 0a1020
run shader            glslViewer    shader
run shadertoy         "$BROWSER"    shadertoy

# Web pages, with each browser
run web               "$BROWSER"    web
run web-firefox       firefox       web          --browser firefox

# A snapshot of the desktop
run blur              grim          blur         --dim 30 60

# --- systemd-inhibit: no blanking while it holds, blanking after ------------
if [[ -z $ONLY || systemd-inhibit == *"$ONLY"* ]]; then
    if ! command -v systemd-inhibit >/dev/null; then
        printf '  %-18s skipped (systemd-inhibit not installed)\n' systemd-inhibit
        results+=("systemd-inhibit|skipped: systemd-inhibit not installed")
    else
        hold=$((IDLE + 5))
        printf '▶ %-18s inhibited for %ss: must NOT blank until then...\n' systemd-inhibit "$hold"
        systemd-inhibit --what=idle --who=wayvoid-demo --why=test sleep "$hold" &
        sleep 0.5
        "$W" "$IDLE" blank 2> "$LOGS/systemd-inhibit.log" &
        pid=$!
        sleep $((hold - 1))
        early=$(grep -c "screen blanked" "$LOGS/systemd-inhibit.log")
        sleep $((IDLE + 3))
        late=$(grep -c "screen blanked" "$LOGS/systemd-inhibit.log")
        kill "$pid" 2>/dev/null
        wait "$pid" 2>/dev/null
        pid=
        if ((early > 0)); then v="FAIL: blanked while inhibited"
        elif ((late == 0)); then v="FAIL: never blanked after the inhibitor ended"
        else v=ok
        fi
        results+=("systemd-inhibit|$v")
    fi
fi

# --- Summary ------------------------------------------------------------------
echo
echo "Summary (logs in $LOGS):"
for r in "${results[@]}"; do
    printf '  %-18s %s\n' "${r%%|*}" "${r#*|}"
done
echo
echo "Sample files and logs are in $DIR; delete it when done."
echo "Browser profiles of the web themes are in ${XDG_CACHE_HOME:-$HOME/.cache}/wayvoid."
